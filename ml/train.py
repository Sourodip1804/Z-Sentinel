MODEL_VERSION = "ZS-PIPE-1.0"


def generate_synthetic(n: int = 8000, seed: int = 42) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    categories = np.array(MERCHANT_CATEGORIES)
    merchant = rng.choice(categories, size=n, p=[0.22, 0.12, 0.08, 0.18, 0.12, 0.18, 0.10])
    amount = np.clip(rng.lognormal(mean=4.2, sigma=1.1, size=n), 5, 20000)
    hour = rng.integers(0, 24, size=n)
    device_novelty = rng.binomial(1, 0.18, size=n).astype(float)
    location_deviation = np.clip(rng.beta(1.4, 4.5, size=n), 0, 1)
    velocity = rng.poisson(2, size=n).astype(float)
    unusual_time = np.isin(hour, [0, 1, 2, 3, 4, 5, 23]).astype(float)

    risk = (
        0.00012 * amount
        + 1.6 * device_novelty
        + 1.8 * location_deviation
        + 0.18 * velocity
        + 1.4 * unusual_time
        + np.where(np.isin(merchant, ["online", "electronics", "travel"]), 0.9, 0.0)
        + rng.normal(0, 0.35, size=n)
        - 3.8
    )
    probability = 1 / (1 + np.exp(-risk))
    labels = rng.binomial(1, np.clip(probability, 0.01, 0.85))
    frame = pd.DataFrame(
        {
            "amount": amount.round(2),
            "hour_of_day": hour,
            "device_novelty": device_novelty,
            "location_deviation": location_deviation.round(4),
            "transaction_velocity": velocity,
            "unusual_time": unusual_time,
            "merchant_category": merchant,
            "is_fraud": labels,
        }
    )
    return training_frame(frame)


def load_dataset() -> tuple[pd.DataFrame, str]:
    if PUBLIC_CSV.exists():
        frame = training_frame(pd.read_csv(PUBLIC_CSV))
        return frame, f"local file {PUBLIC_CSV.name} (user-supplied labelled CSV)"
    frame = generate_synthetic()
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    frame.to_csv(SYNTHETIC_CSV, index=False)
    return frame, (
        "synthetic development set generated by ml/train.py. "
        "It is not a public labelled fraud corpus and must not be reported as real-world performance."
    )


def split_frame(frame: pd.DataFrame):
    x = frame[MODEL_FEATURES]
    y = frame["is_fraud"]
    x_train, x_temp, y_train, y_temp = train_test_split(
        x, y, test_size=0.30, stratify=y, random_state=42
    )
    x_valid, x_test, y_valid, y_test = train_test_split(
        x_temp, y_temp, test_size=0.50, stratify=y_temp, random_state=42
    )
    return x_train, x_valid, x_test, y_train, y_valid, y_test


def build_preprocess() -> ColumnTransformer:
    numeric = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
        ]
    )
    categorical = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
        ]
    )
    return ColumnTransformer(
        transformers=[
            ("num", numeric, NUMERIC_FEATURES),
            ("cat", categorical, CATEGORICAL_FEATURES),
        ]
    )


def candidate_models(quick: bool = False) -> dict[str, object]:
    trees = 40 if quick else 120
    models = {
        "logreg": LogisticRegression(
            max_iter=400,
            class_weight="balanced",
            random_state=42,
        ),
        "random_forest": RandomForestClassifier(
            n_estimators=trees,
            max_depth=10,
            min_samples_leaf=4,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        ),
    }
    try:
        from xgboost import XGBClassifier

        models["xgboost"] = XGBClassifier(
            n_estimators=trees,
            max_depth=5,
            learning_rate=0.08,
            subsample=0.9,
            colsample_bytree=0.9,
            eval_metric="logloss",
            random_state=42,
            n_jobs=-1,
        )
    except Exception as exc:
        print(f"XGBoost unavailable ({exc}); skipping that candidate.")
    return models


def classification_metrics(y_true, proba, threshold: float) -> dict:
    y_pred = (proba >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    fpr = fp / (fp + tn) if (fp + tn) else 0.0
    fnr = fn / (fn + tp) if (fn + tp) else 0.0
    return {
        "threshold": threshold,
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "roc_auc": float(roc_auc_score(y_true, proba)),
        "pr_auc": float(average_precision_score(y_true, proba)),
        "false_positive_rate": float(fpr),
        "false_negative_rate": float(fnr),
        "confusion_matrix": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
    }


def tune_threshold(y_true, proba, max_fpr: float = 0.08) -> float:
    precision, recall, thresholds = precision_recall_curve(y_true, proba)
    best_f1 = -1.0
    best_t = 0.5
    for threshold in thresholds:
        metrics = classification_metrics(y_true, proba, float(threshold))
        if metrics["false_positive_rate"] <= max_fpr and metrics["f1"] > best_f1:
            best_f1 = metrics["f1"]
            best_t = float(threshold)
    if best_f1 < 0:
        f1_scores = 2 * (precision * recall) / np.clip(precision + recall, 1e-9, None)
        idx = int(np.nanargmax(f1_scores[:-1])) if len(thresholds) else 0
        best_t = float(thresholds[idx]) if len(thresholds) else 0.5
    return round(min(max(best_t, 0.15), 0.85), 4)


def fit_scale_pos_weight(y_train) -> float:
    negatives = int((y_train == 0).sum())
    positives = int((y_train == 1).sum())
    return negatives / max(positives, 1)


def main(quick: bool = False) -> Path:
    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    frame, source = load_dataset()
    x_train, x_valid, x_test, y_train, y_valid, y_test = split_frame(frame)
    scale_pos = fit_scale_pos_weight(y_train)
    comparison = {}
    fitted = {}
    for name, estimator in candidate_models(quick=quick).items():
        if name == "xgboost":
            estimator.set_params(scale_pos_weight=scale_pos)
        pipe = Pipeline(
            steps=[
                ("preprocess", build_preprocess()),
                ("model", estimator),
            ]
        )
        pipe.fit(x_train, y_train)
        valid_proba = pipe.predict_proba(x_valid)[:, 1]
        comparison[name] = classification_metrics(y_valid, valid_proba, 0.5)
        fitted[name] = pipe
        print(f"{name} valid PR-AUC={comparison[name]['pr_auc']:.4f} F1@0.5={comparison[name]['f1']:.4f}")

    selected_name = max(comparison, key=lambda key: comparison[key]["pr_auc"])
    selected = fitted[selected_name]
    raw_valid = selected.predict_proba(x_valid)[:, 1]
    calibrator = IsotonicRegression(out_of_bounds="clip")
    try:
        calibrator.fit(raw_valid, y_valid.to_numpy())
        valid_proba = calibrator.predict(raw_valid)
        calibrated_flag = True
    except Exception as exc:
        print(f"Calibration skipped ({exc}); using raw scores.")
        calibrator = None
        valid_proba = raw_valid
        calibrated_flag = False

    high_threshold = tune_threshold(y_valid, valid_proba)
    medium_threshold = round(max(0.12, high_threshold * 0.45), 4)
    raw_test = selected.predict_proba(x_test)[:, 1]
    test_proba = calibrator.predict(raw_test) if calibrator is not None else raw_test
    test_metrics = classification_metrics(y_test, test_proba, high_threshold)
    final_pipeline = selected

    artifact_path = ARTIFACT_DIR / "zsentinel_pipeline_v1.joblib"
    bundle = {
        "pipeline": final_pipeline,
        "calibrator": calibrator,
        "model_version": MODEL_VERSION,
        "selected_model": selected_name,
        "feature_contract_version": FEATURE_CONTRACT_VERSION,
        "features": MODEL_FEATURES,
        "medium_threshold": medium_threshold,
        "high_threshold": high_threshold,
        "calibrated": calibrated_flag,
        "data_source": source,
        "class_distribution": {
            "train_positive_rate": float(y_train.mean()),
            "valid_positive_rate": float(y_valid.mean()),
            "test_positive_rate": float(y_test.mean()),
        },
    }
    joblib.dump(bundle, artifact_path)
    evaluation = {
        "data_source": source,
        "disclaimer": (
            "Metrics below are for this development dataset only. "
            "Do not claim validated real-world fraud performance if the source is synthetic."
        ),
        "selected_model": selected_name,
        "model_version": MODEL_VERSION,
        "validation_comparison": comparison,
        "test_metrics": test_metrics,
        "medium_threshold": medium_threshold,
        "high_threshold": high_threshold,
        "calibrated": calibrated_flag,
        "feature_contract": contract_metadata(),
        "n_train": int(len(x_train)),
        "n_valid": int(len(x_valid)),
        "n_test": int(len(x_test)),
    }
    (ARTIFACT_DIR / "evaluation.json").write_text(json.dumps(evaluation, indent=2), encoding="utf-8")
    (ARTIFACT_DIR / "metadata.json").write_text(
        json.dumps(
            {
                "model_version": MODEL_VERSION,
                "artifact": str(artifact_path.name),
                "selected_model": selected_name,
                "data_source": source,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"Saved {artifact_path}")
    print(f"Selected {selected_name} test PR-AUC={test_metrics['pr_auc']:.4f}")
    return artifact_path


if __name__ == "__main__":
    quick = "--quick" in sys.argv
    main(quick=quick)
